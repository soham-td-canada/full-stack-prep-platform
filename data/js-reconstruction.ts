import type { Concept, Difficulty, Question, QuestionType, StructuredField } from "@/lib/model";

const text = (id: string, label: string, ...accepted: string[]): StructuredField =>
  ({ id, label, kind: "text", accepted });
const choose = (id: string, label: string, choices: string[], correct: string[], multiple = false,
  tag?: string, severity?: "critical"): StructuredField =>
  ({ id, label, kind: "select", choices: choices.map((value) => ({ id: value, label: value })),
    correct, multiple, misconceptionTag: tag, severity });
const one = (label: string, choices: string[], correct: string, tag?: string) =>
  choose("answer", label, choices, [correct], false, tag);

function exercise(id: string, type: QuestionType, concepts: Concept[], difficulty: Difficulty, prompt: string,
  fields: StructuredField[], explanation: string, options: { depth?: "core" | "optional"; code?: string } = {}): Question {
  return {
    id: `js-recon-${id}`, module: "javascript-typescript", mode: "reconstruction", concepts, difficulty,
    prompt, code: options.code, structured: { type, fields }, depth: options.depth ?? "core",
    answer: fields.map((field) => `${field.label}: ${field.kind === "text" ? field.accepted[0] : field.correct.join(", ")}`).join("\n"),
    explanation, misconception: { prompt: `Recall the demonstrated concept: ${prompt}`, answer: explanation },
  };
}

